/**
 * The entry module the `zuke` binary is compiled from.
 *
 * A `deno compile` binary cannot import a module it was not compiled with, so
 * a binary compiled from `jsr:@zuke/cli` alone had to find a Deno to run a
 * Python build's engine, and the engine could not have reached its wrappers
 * from inside it anyway. The binary is compiled from this entry instead: the
 * published `@zuke/cli`, `@zuke/engine` and every released wrapper, each at
 * the exact version this release commit holds, behind literal imports the
 * compile embeds. Started normally it is the CLI, carrying that engine;
 * started by the CLI with `EMBEDDED_ENGINE_ENV` set it is the engine, with
 * `tool.call` served from the embedded wrappers. Core's `run` is called here,
 * in the entry module, because it acts only for the program's own module.
 *
 * @module
 */

import { FileTasks } from "@zuke/core";
import { cliSpecifier } from "./cli_compile.ts";
import { localVersion } from "./packages.ts";
import { WRAPPER_PACKAGES } from "./tool_spec.ts";

/** One wrapper release the binary embeds, and the specifier it is imported by. */
export interface EmbeddedWrapper {
  /** The package's name after `@zuke/`. */
  readonly name: string;
  /** Its exact release. */
  readonly version: string;
  /** The specifier the entry imports it by. */
  readonly specifier: string;
}

/** What the entry is rendered from: specifiers for the three engine parts, and the wrappers. */
export interface BinaryEntry {
  /** `@zuke/cli`'s specifier. */
  readonly cli: string;
  /** `@zuke/engine`'s specifier. */
  readonly engine: string;
  /** The engine release, which the CLI checks a project's pin against. */
  readonly engineVersion: string;
  /**
   * `@zuke/core`'s specifier: the range the engine itself imports, so `run`
   * and the engine's materialised `Build` resolve to the one core.
   */
  readonly core: string;
  /** The core release this checkout holds, which the compile resolves that range to. */
  readonly coreVersion: string;
  /** Every wrapper release the binary serves `tool.call` from. */
  readonly wrappers: readonly EmbeddedWrapper[];
}

/** A string as a TypeScript literal. */
function literal(text: string): string {
  return JSON.stringify(text);
}

/** Render the entry module for `entry`. Pure: the same input, the same text. */
export function binaryEntry(entry: BinaryEntry): string {
  const releases = entry.wrappers.map((w) =>
    `  ${literal(w.name)}: {\n    version: ${literal(w.version)},\n` +
    `    load: () => import(${literal(w.specifier)}),\n  },\n`
  ).join("");
  return `// Copyright (c) 2026 the Zuke contributors
// SPDX-License-Identifier: MIT

// The compiled zuke binary's entry, generated by build/cli_binary.ts.

import {
  binaryMain,
  EMBEDDED_ENGINE_ENV,
  FORWARDED_ENV,
} from ${literal(entry.cli)};
import {
  embeddedTools,
  hostedBuild,
  servesRelease,
} from ${literal(entry.engine)};
import { run } from ${literal(entry.core)};

const ENGINE = ${literal(entry.engineVersion)};

const RELEASES = {
${releases}};

if (Deno.env.get(EMBEDDED_ENGINE_ENV) === "1") {
  // This process is the engine for the project's worker. Nothing the build
  // starts inherits either switch: a zuke a body runs forwards afresh, its
  // launcher included, since this process is no launcher.
  Deno.env.delete(EMBEDDED_ENGINE_ENV);
  Deno.env.delete(FORWARDED_ENV);
  await run(await hostedBuild(embeddedTools(RELEASES)));
} else {
  Deno.exit(
    await binaryMain(Deno.args, {
      version: ENGINE,
      program: Deno.execPath(),
      serves: (pin) => servesRelease(ENGINE, pin),
    }),
  );
}
`;
}

/** A package's import map entry for `@zuke/core`, as its `deno.json` declares it. */
async function coreImport(pkg: string): Promise<string> {
  const config: unknown = await FileTasks.readJson(`packages/${pkg}/deno.json`);
  const imports = typeof config === "object" && config !== null
    ? Reflect.get(config, "imports")
    : undefined;
  const core = typeof imports === "object" && imports !== null
    ? Reflect.get(imports, "@zuke/core")
    : undefined;
  if (typeof core !== "string") {
    throw new Error(`packages/${pkg}/deno.json imports no @zuke/core`);
  }
  return core;
}

/**
 * The entry a release's binaries are compiled from: `@zuke/cli` at
 * `version`, and the engine and every wrapper at the versions this checkout
 * holds, from JSR. A wrapper still at `0.0.0` has never been released, so it
 * is not embedded.
 */
export async function releaseEntry(version: string): Promise<BinaryEntry> {
  const engineVersion = await localVersion("engine");
  const wrappers: EmbeddedWrapper[] = [];
  for (const name of WRAPPER_PACKAGES) {
    const release = await localVersion(name);
    if (release === "0.0.0") continue;
    wrappers.push({
      name,
      version: release,
      specifier: `jsr:@zuke/${name}@${release}`,
    });
  }
  return {
    cli: cliSpecifier(version),
    engine: `jsr:@zuke/engine@${engineVersion}`,
    engineVersion,
    core: await coreImport("engine"),
    coreVersion: await localVersion("core"),
    wrappers,
  };
}

/** Every package a release's entry imports, with its release, for the listing wait. */
export function embeddedReleases(
  entry: BinaryEntry,
  version: string,
): Array<[string, string]> {
  return [
    ["cli", version],
    ["engine", entry.engineVersion],
    ["core", entry.coreVersion],
    ...entry.wrappers.map((w): [string, string] => [w.name, w.version]),
  ];
}
