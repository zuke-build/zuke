/**
 * Type-check the workspace through one generated entry module.
 *
 * The `check` target used to hand `deno check` every file as an argument —
 * about a thousand paths, which on Windows crossed the 32,767-character limit
 * on a command line and failed with `os error 206` before checking anything.
 * The list only grows, so trimming it would just move the cliff. Instead the
 * files become side-effect imports of one module, written to a dot-prefixed
 * scratch directory inside the workspace (so `deno.json` and the workspace
 * resolve exactly as for the files themselves, and a concurrent `format`
 * skips it), and `deno check` gets that one path. The type-checker sees the
 * same program either way: every file is a root of the graph it builds.
 *
 * @module
 */

import type { CommandOutput } from "@zuke/core/shell";
import { DenoTasks } from "@zuke/deno";

/**
 * The text of a module importing each of `files` for its side effects, from a
 * module one directory below the workspace root. Paths are workspace-relative
 * and may use either separator; the specifiers always use `/`.
 */
export function checkEntry(files: readonly string[]): string {
  const lines = [
    "// Copyright (c) 2026 the Zuke contributors",
    "// SPDX-License-Identifier: MIT",
    "",
    "// Generated by build/check_entry.ts for one `deno check` run; removed after.",
    "",
  ];
  for (const file of files) {
    lines.push(`import ${JSON.stringify(`../${file.replaceAll("\\", "/")}`)};`);
  }
  return `${lines.join("\n")}\n`;
}

/**
 * Type-check `files` (workspace-relative) as one program through a generated
 * entry module, removing it afterwards. Throws when the check fails, as
 * `DenoTasks.check` does.
 */
export async function checkAll(
  files: readonly string[],
): Promise<CommandOutput> {
  const dir = await Deno.makeTempDir({ dir: Deno.cwd(), prefix: ".check-" });
  try {
    const entry = `${dir}/entry.ts`;
    await Deno.writeTextFile(entry, checkEntry(files));
    return await DenoTasks.check((s) => s.frozen().paths(entry));
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
}
