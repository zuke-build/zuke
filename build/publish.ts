/**
 * Release/publish helpers: where build-time CLIs are installed, the on-demand
 * CLI installer, and the timeout-guarded JSR publish for one package.
 */

import { type AbsolutePath, FileTasks, repoRoot } from "@zuke/core";
import { CommandTimeoutError } from "@zuke/core/shell";
import { delay } from "../packages/core/src/internal.ts";
import { DenoRunSettings, DenoTasks } from "@zuke/deno";

/**
 * Where build-time CLIs are installed on demand. Gitignored (`/.zuke/`), so the
 * install is a transient, per-run artifact.
 */
export const TOOLS_ROOT: AbsolutePath = repoRoot(".zuke", "tools");

/** How long to wait for one `deno publish` before treating it as stalled. */
export const PUBLISH_TIMEOUT_MS = 180_000;

/** How many times {@link publishOne} runs `deno publish` for one version. */
export const PUBLISH_ATTEMPTS = 3;

/** How long {@link publishOne} waits between checks that a version landed. */
export const LANDING_POLL_MS = 30_000;

/**
 * How many checks {@link publishOne} makes after an upload that timed out:
 * JSR accepted it and is still processing, which has taken from minutes to
 * the better part of an hour when its queue is slow (#855). Ten checks thirty
 * seconds apart give it five minutes before the next attempt.
 */
export const LANDING_POLLS_AFTER_TIMEOUT = 10;

/**
 * How many checks {@link publishOne} makes after an attempt that failed
 * outright. A failure can come after the upload was accepted (a 503 while
 * deno polled the publishing status), so it is worth a short look — but a
 * failure deno decided locally will not land however long it is given.
 */
export const LANDING_POLLS_AFTER_ERROR = 2;

/**
 * Provision an npm-distributed CLI as a launcher under {@link TOOLS_ROOT} and
 * return the absolute path to it. cspell and release-please ship only on npm, so
 * the build provisions them itself rather than assuming a global binary —
 * keeping the gate runnable without a separate setup step. The caller's `permit`
 * lambda grants the launcher its permissions.
 *
 * The launcher runs `deno run --frozen <module>` from the repository root, so
 * npm resolution goes through the workspace `deno.lock`: the tool's whole
 * transitive tree is pinned to the integrity hashes committed there, and a tree
 * that no longer matches the lock fails the build instead of quietly resolving
 * something new. `deno install --global` cannot give that guarantee — it ignores
 * the discovered workspace config and lock (even with `--lock`/`--frozen`
 * passed) and resolves into a throwaway lockfile inside its own install root, so
 * every run re-resolves the tree unpinned. Adding a tool here therefore means
 * caching its specifier into `deno.lock` (`deno cache npm:<tool>@<version>`) and
 * committing that, or the first `--frozen` run fails.
 */
export async function installCli(
  module: string,
  name: string,
  permit: (s: DenoRunSettings) => DenoRunSettings,
): Promise<AbsolutePath> {
  const onWindows = Deno.build.os === "windows";
  const argv = permit(new DenoRunSettings().frozen()).script(module).argv();
  const launcher = TOOLS_ROOT("bin", onWindows ? `${name}.cmd` : name);
  await FileTasks.createDirectory(TOOLS_ROOT("bin"));
  await FileTasks.writeText(launcher, launcherScript(argv, onWindows));
  // The generated launcher has to be executable to be spawned as a tool path.
  if (!onWindows) await Deno.chmod(String(launcher), 0o755);
  return launcher;
}

/**
 * The text of a generated launcher: `argv` run from the repository root (so
 * `deno` discovers the workspace `deno.lock`) with the caller's own arguments
 * appended. Every word is quoted, because the repository path is arbitrary.
 */
export function launcherScript(argv: string[], onWindows: boolean): string {
  const root = String(repoRoot());
  if (onWindows) {
    const line = argv.map((word) => `"${word.replaceAll('"', '""')}"`).join(
      " ",
    );
    return [
      "@echo off",
      ":: generated by zuke — runs the tool through the workspace deno.lock",
      `cd /d "${root}" || exit /b 1`,
      `${line} %*`,
      "",
    ].join("\r\n");
  }
  const quote = (word: string) => `'${word.replaceAll("'", `'\\''`)}'`;
  return [
    "#!/bin/sh",
    "# generated by zuke — runs the tool through the workspace deno.lock",
    `cd ${quote(root)} || exit 1`,
    `exec ${argv.map(quote).join(" ")} "$@"`,
    "",
  ].join("\n");
}

/**
 * Publish one package with a timeout. Returns `true` on success, or `false` if
 * `deno publish` stalled past the timeout and was killed. JSR's post-upload
 * finalization (provenance) occasionally hangs *after* the upload completes, so
 * the caller re-checks JSR before deciding whether a `false` is fatal.
 *
 * `--allow-dirty`: release-please bumps `deno.json` versions on the release PR
 * branch, so the merged tree should already be clean here. It is kept as a
 * backstop; for the strongest "published == committed source" guarantee (which
 * provenance otherwise gives) drop it once a real release confirms the publish
 * tree is clean. See SECURITY.md.
 */
export async function publishPackage(pkg: string): Promise<boolean> {
  try {
    await DenoTasks.publish((s) =>
      s.allowDirty().cwd(`packages/${pkg}`).killAfter(PUBLISH_TIMEOUT_MS)
    );
    return true;
  } catch (error) {
    if (error instanceof CommandTimeoutError) return false;
    throw error;
  }
}

/**
 * The dependencies {@link publishOne} needs, injected so its skip/publish/
 * re-check decision is unit-testable without a real `deno publish` or a
 * network call to JSR.
 */
export interface PublishOneDeps {
  /** Whether `pkg`@`version` is already on JSR. */
  isPublished(pkg: string, version: string): Promise<boolean>;
  /** Publish `pkg`; `false` means the upload timed out (see {@link publishPackage}). */
  publishPackage(pkg: string): Promise<boolean>;
  /** Report an in-progress/skip status line. */
  info(message: string): void;
  /** Report that a stalled or failed upload is confirmed to have landed. */
  success(message: string): void;
  /** Wait `ms` milliseconds between checks. */
  wait(ms: number): Promise<void>;
}

/**
 * Publish one package's pending version to JSR, which the walk in
 * {@link publishAllTo} has found missing there: run `deno publish` up to
 * {@link PUBLISH_ATTEMPTS} times. After an
 * attempt that times out or fails, JSR is checked for a while before the next
 * one: an upload JSR accepted keeps processing after deno gives up on it — its
 * queue has taken the better part of an hour (#855) — so a stalled attempt is
 * not necessarily a failed publish, and running `deno publish` again for an
 * accepted version just waits on the same JSR task.
 *
 * @throws {Error} naming the package/version and the last attempt's outcome,
 * if no attempt lands it on JSR.
 */
export async function publishOne(
  pkg: string,
  version: string,
  deps: PublishOneDeps,
): Promise<void> {
  const name = `@zuke/${pkg}@${version}`;
  const onJsr = () => deps.isPublished(`@zuke/${pkg}`, version);
  let outcome = "";
  for (let attempt = 1; attempt <= PUBLISH_ATTEMPTS; attempt++) {
    deps.info(
      attempt === 1
        ? `Publishing ${name} to JSR...`
        : `Publishing ${name} to JSR again (attempt ${attempt} of ` +
          `${PUBLISH_ATTEMPTS})...`,
    );
    let polls = LANDING_POLLS_AFTER_TIMEOUT;
    try {
      if (await deps.publishPackage(pkg)) return;
      outcome = "the upload timed out";
    } catch (error) {
      outcome = error instanceof Error ? error.message : String(error);
      polls = LANDING_POLLS_AFTER_ERROR;
    }
    for (let poll = 0; poll < polls; poll++) {
      if (await onJsr()) {
        deps.success(`${name} reached JSR after ${outcome}.`);
        return;
      }
      await deps.wait(LANDING_POLL_MS);
    }
  }
  throw new Error(
    `Publishing ${name} did not reach JSR after ${PUBLISH_ATTEMPTS} ` +
      `attempts; the last: ${outcome}.`,
  );
}

/** Wait `ms` milliseconds: the real {@link PublishOneDeps.wait}. */
export const waitFor: (ms: number) => Promise<void> = delay;

/**
 * A registry the packages are released to, for {@link publishAllTo}: what
 * differs between JSR and npm.
 */
export interface PublishRegistry {
  /** The registry's name in messages: `JSR`, `npm`. */
  name: string;
  /** The registry's name for workspace package `pkg`: `@zuke/core`. */
  packageName(pkg: string): string;
  /** Whether `pkg`@`version` is already on the registry. */
  isPublished(pkg: string, version: string): Promise<boolean>;
  /**
   * Why `pkg`@`version`, not yet on the registry, waits rather than publishes
   * now, or `null` when it is due. A held version is no failure: it is
   * reported and skipped, and so is every package that depends on it.
   */
  held?(pkg: string, version: string): Promise<string | null>;
  /** Publish `pkg`@`version`; throws if it did not land. */
  publish(pkg: string, version: string): Promise<void>;
}

/** What {@link publishAllTo} needs besides a {@link PublishRegistry}. */
export interface ReleaseWalkDeps {
  /** The version `pkg` releases from this commit; `"0.0.0"` means none yet. */
  versionOf(pkg: string): Promise<string>;
  /** Report a skip or progress line. */
  info(message: string): void;
  /** Report a version that did not land, and why. */
  failed(message: string): void;
}

/**
 * The dependencies {@link publishAll} needs beyond {@link PublishOneDeps}:
 * each package's version, and where a version that did not land is reported.
 */
export interface PublishAllDeps extends PublishOneDeps, ReleaseWalkDeps {}

/** Where a package version stands on a registry: see {@link standingOf}. */
export type Standing =
  | { kind: "published" }
  | { kind: "held"; reason: string }
  | { kind: "due" };

/**
 * Where `pkg`@`version` stands on `registry`, the one decision both the
 * publish walk and npm's verification make: already `published`; `held`,
 * because a workspace package it needs (core and `dependencies[pkg]`) is in
 * `held` or the registry holds it, in which case `pkg` joins `held`; or `due`.
 * Call it in `packages` order, so a dependency is decided before its
 * dependents.
 */
export async function standingOf(
  pkg: string,
  version: string,
  dependencies: Readonly<Record<string, readonly string[]>>,
  held: Set<string>,
  registry: PublishRegistry,
): Promise<Standing> {
  if (await registry.isPublished(pkg, version)) return { kind: "published" };
  const waiting = needsOf(pkg, dependencies).find((d) => held.has(d));
  const reason = waiting !== undefined
    ? `its dependency ${registry.packageName(waiting)} waits.`
    : await registry.held?.(pkg, version) ?? null;
  if (reason === null) return { kind: "due" };
  held.add(pkg);
  return { kind: "held", reason };
}

/** The workspace packages `pkg` needs on a registry before it: core and its dependencies. */
function needsOf(
  pkg: string,
  dependencies: Readonly<Record<string, readonly string[]>>,
): string[] {
  return pkg === "core" ? [] : ["core", ...(dependencies[pkg] ?? [])];
}

/**
 * Release every package's pending version to `registry`, in `packages` order
 * (core first, each package after the workspace packages it depends on). For
 * each: `0.0.0` is skipped, a version already on the registry is skipped, one
 * the registry holds (or whose dependency it holds) waits without failing, and
 * one whose dependency did not land in this walk is not tried, since it may
 * need the dependency's new version. A package that fails is reported and the
 * walk carries on, so one stuck package cannot hold back the rest of the
 * release (#849). Every package depends on `core`; `dependencies` lists the
 * others (`PACKAGE_DEPENDENCIES`).
 *
 * @throws {Error} after the last package, naming every version that did not
 * land.
 */
export async function publishAllTo(
  packages: readonly string[],
  dependencies: Readonly<Record<string, readonly string[]>>,
  deps: ReleaseWalkDeps,
  registry: PublishRegistry,
): Promise<void> {
  const missing = new Set<string>();
  const held = new Set<string>();
  const failures: string[] = [];
  for (const pkg of packages) {
    const version = await deps.versionOf(pkg);
    if (version === "0.0.0") {
      deps.info(`${registry.packageName(pkg)} has no released version yet.`);
      continue;
    }
    const name = `${registry.packageName(pkg)}@${version}`;
    try {
      // A version already on the registry needs nothing from its dependencies.
      const standing = await standingOf(
        pkg,
        version,
        dependencies,
        held,
        registry,
      );
      if (standing.kind === "published") {
        deps.info(`${name} is already on ${registry.name}.`);
        continue;
      }
      if (standing.kind === "held") {
        deps.info(`${name} waits: ${standing.reason}`);
        continue;
      }
      const blocker = needsOf(pkg, dependencies).find((dependency) =>
        missing.has(dependency)
      );
      if (blocker !== undefined) {
        throw new Error(
          `its dependency ${registry.packageName(blocker)} did not land.`,
        );
      }
      await registry.publish(pkg, version);
    } catch (error) {
      const reason = error instanceof Error ? error.message : String(error);
      deps.failed(`${name} did not publish: ${reason}`);
      missing.add(pkg);
      failures.push(name);
    }
  }
  if (failures.length > 0) {
    throw new Error(
      `${failures.length} package version(s) did not reach ${registry.name}: ` +
        `${failures.join(", ")}. Re-run once the cause is fixed — a version ` +
        `already on ${registry.name} is skipped.`,
    );
  }
}

/** Publish every package's pending version to JSR: {@link publishAllTo} with `deno publish`. */
export function publishAll(
  packages: readonly string[],
  dependencies: Readonly<Record<string, readonly string[]>>,
  deps: PublishAllDeps,
): Promise<void> {
  return publishAllTo(packages, dependencies, deps, {
    name: "JSR",
    packageName: (pkg) => `@zuke/${pkg}`,
    isPublished: (pkg, version) => deps.isPublished(`@zuke/${pkg}`, version),
    publish: (pkg, version) => publishOne(pkg, version, deps),
  });
}
