/**
 * Release/publish helpers: where build-time CLIs are installed, the on-demand
 * CLI installer, and the timeout-guarded JSR publish for one package.
 */

import { type AbsolutePath, FileTasks, repoRoot } from "@zuke/core";
import { CommandTimeoutError } from "@zuke/core/shell";
import { DenoRunSettings, DenoTasks } from "@zuke/deno";

/**
 * Where build-time CLIs are installed on demand. Gitignored (`/.zuke/`), so the
 * install is a transient, per-run artifact.
 */
export const TOOLS_ROOT: AbsolutePath = repoRoot(".zuke", "tools");

/**
 * The pinned Codecov CLI version `coverageUpload` downloads. Pinned (never
 * `latest`) so the build is reproducible and fetches a fixed artifact rather
 * than a moving target; bump it deliberately. Codecov serves versioned binaries
 * at `cli.codecov.io/v<semver>/<platform>/codecov`.
 */
export const CODECOV_CLI_VERSION = "v11.2.8";

/** How long to wait for one `deno publish` before treating it as stalled. */
export const PUBLISH_TIMEOUT_MS = 180_000;

/**
 * Provision an npm-distributed CLI as a launcher under {@link TOOLS_ROOT} and
 * return the absolute path to it. cspell and release-please ship only on npm, so
 * the build provisions them itself rather than assuming a global binary —
 * keeping the gate runnable without a separate setup step. The caller's `permit`
 * lambda grants the launcher its permissions.
 *
 * The launcher runs `deno run --frozen <module>` from the repository root, so
 * npm resolution goes through the workspace `deno.lock`: the tool's whole
 * transitive tree is pinned to the integrity hashes committed there, and a tree
 * that no longer matches the lock fails the build instead of quietly resolving
 * something new. `deno install --global` cannot give that guarantee — it ignores
 * the discovered workspace config and lock (even with `--lock`/`--frozen`
 * passed) and resolves into a throwaway lockfile inside its own install root, so
 * every run re-resolves the tree unpinned. Adding a tool here therefore means
 * caching its specifier into `deno.lock` (`deno cache npm:<tool>@<version>`) and
 * committing that, or the first `--frozen` run fails.
 */
export async function installCli(
  module: string,
  name: string,
  permit: (s: DenoRunSettings) => DenoRunSettings,
): Promise<AbsolutePath> {
  const onWindows = Deno.build.os === "windows";
  const argv = permit(new DenoRunSettings().frozen()).script(module).argv();
  const launcher = TOOLS_ROOT("bin", onWindows ? `${name}.cmd` : name);
  await FileTasks.createDirectory(TOOLS_ROOT("bin"));
  await FileTasks.writeText(launcher, launcherScript(argv, onWindows));
  // The generated launcher has to be executable to be spawned as a tool path.
  if (!onWindows) await Deno.chmod(String(launcher), 0o755);
  return launcher;
}

/**
 * The text of a generated launcher: `argv` run from the repository root (so
 * `deno` discovers the workspace `deno.lock`) with the caller's own arguments
 * appended. Every word is quoted, because the repository path is arbitrary.
 */
export function launcherScript(argv: string[], onWindows: boolean): string {
  const root = String(repoRoot());
  if (onWindows) {
    const line = argv.map((word) => `"${word.replaceAll('"', '""')}"`).join(
      " ",
    );
    return [
      "@echo off",
      ":: generated by zuke — runs the tool through the workspace deno.lock",
      `cd /d "${root}" || exit /b 1`,
      `${line} %*`,
      "",
    ].join("\r\n");
  }
  const quote = (word: string) => `'${word.replaceAll("'", `'\\''`)}'`;
  return [
    "#!/bin/sh",
    "# generated by zuke — runs the tool through the workspace deno.lock",
    `cd ${quote(root)} || exit 1`,
    `exec ${argv.map(quote).join(" ")} "$@"`,
    "",
  ].join("\n");
}

/**
 * Publish one package with a timeout. Returns `true` on success, or `false` if
 * `deno publish` stalled past the timeout and was killed. JSR's post-upload
 * finalization (provenance) occasionally hangs *after* the upload completes, so
 * the caller re-checks JSR before deciding whether a `false` is fatal.
 *
 * `--allow-dirty`: release-please bumps `deno.json` versions on the release PR
 * branch, so the merged tree should already be clean here. It is kept as a
 * backstop; for the strongest "published == committed source" guarantee (which
 * provenance otherwise gives) drop it once a real release confirms the publish
 * tree is clean. See SECURITY.md.
 */
export async function publishPackage(pkg: string): Promise<boolean> {
  try {
    await DenoTasks.publish((s) =>
      s.allowDirty().cwd(`packages/${pkg}`).killAfter(PUBLISH_TIMEOUT_MS)
    );
    return true;
  } catch (error) {
    if (error instanceof CommandTimeoutError) return false;
    throw error;
  }
}

/**
 * The dependencies {@link publishOne} needs, injected so its skip/publish/
 * re-check decision is unit-testable without a real `deno publish` or a
 * network call to JSR.
 */
export interface PublishOneDeps {
  /** Whether `pkg`@`version` is already on JSR. */
  isPublished(pkg: string, version: string): Promise<boolean>;
  /** Publish `pkg`; `false` means the upload timed out (see {@link publishPackage}). */
  publishPackage(pkg: string): Promise<boolean>;
  /** Report an in-progress/skip status line. */
  info(message: string): void;
  /** Report that a stalled publish is confirmed to have landed. */
  success(message: string): void;
}

/**
 * Publish one package's pending version to JSR: skip it if already published,
 * otherwise publish it — and, if the publish itself times out, re-check JSR
 * once before deciding whether the timeout was fatal. JSR's post-upload
 * provenance finalization occasionally hangs *after* the upload completes, so
 * a `false` from {@link PublishOneDeps.publishPackage} isn't necessarily a
 * failed publish.
 *
 * @throws {Error} naming the package/version, if the publish times out and the
 * re-check still doesn't find it on JSR.
 */
export async function publishOne(
  pkg: string,
  version: string,
  deps: PublishOneDeps,
): Promise<void> {
  const name = `@zuke/${pkg}@${version}`;
  if (await deps.isPublished(`@zuke/${pkg}`, version)) {
    deps.info(`${name} is already on JSR.`);
    return;
  }
  deps.info(`Publishing ${name} to JSR...`);
  if (await deps.publishPackage(pkg)) return;
  // Timed out: the upload usually lands before JSR's finalization hangs, so a
  // re-check tells us whether it actually published.
  if (await deps.isPublished(`@zuke/${pkg}`, version)) {
    deps.success(`${name} uploaded (provenance stalled).`);
    return;
  }
  throw new Error(`Publishing ${name} timed out before reaching JSR.`);
}
